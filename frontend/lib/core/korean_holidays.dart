/// 표로 관리되는 연도 범위. 이 범위 밖은 고정 공휴일만 표시됩니다.
const koreanHolidayTableYears = (2023, 2030);

/// [date]에 해당하는 공휴일 이름 목록. 공휴일이 아니면 빈 목록.
/// 고정 공휴일과 음력 공휴일이 겹치는 날(예: 어린이날·부처님오신날)은 둘 다 담깁니다.
/// 연·월·일만 보며, 시간대나 UTC 여부는 무시합니다.
List<String> koreanHolidays(DateTime date) {
  final key = (date.month, date.day);
  return [?_fixed[key], ?_byYear[date.year]?[key]];
}

/// [date]가 공휴일이면 이름('설날', '대체공휴일' 등, 겹치면 '·'로 이어 붙임), 아니면 null.
String? koreanHoliday(DateTime date) {
  final names = koreanHolidays(date);
  return names.isEmpty ? null : names.join('·');
}

/// [date]가 공휴일인지 여부.
bool isKoreanHoliday(DateTime date) => koreanHoliday(date) != null;
